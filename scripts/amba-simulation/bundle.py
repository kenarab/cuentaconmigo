#!/usr/bin/env python3
"""Bundle the derived AMBA simulation data next to the prototype as JavaScript files,
so design/prototypes/simulacion-amba/index.html works when opened from disk (file://
blocks fetch) and when published. Public official results, no personal data.

Input: data/private/amba-simulation/{mesas_2023_amba.json, strata_2023_amba.geojson}
(generated by normalize.py and geography.py, hashes checked against the manifest).
Output: design/prototypes/simulacion-amba/data/{mesas.js, strata.js}.

Standard library only.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data/private/amba-simulation"
OUT = ROOT / "design/prototypes/simulacion-amba/data"
FILES = {"mesas_2023_amba.json": ("mesas.js", "AMBA_MESAS"),
         "strata_2023_amba.geojson": ("strata.js", "AMBA_STRATA")}

manifest = json.loads((ROOT / "data/amba-simulation/manifest.json").read_text())
expected = {d["file"]: d["sha256"] for d in manifest["derived"]}
OUT.mkdir(parents=True, exist_ok=True)
for name, (target, var) in FILES.items():
    raw = (SRC / name).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != expected.get(name):
        raise SystemExit(f"{name}: sha256 {digest} does not match the manifest")
    body = f"// Generated by scripts/amba-simulation/bundle.py from {name} (sha256 {digest}).\n"
    body += f"window.{var} = {raw.decode('utf-8')};\n"
    (OUT / target).write_text(body, encoding="utf-8")
    print(f"wrote {OUT / target} ({len(body)} bytes)")
